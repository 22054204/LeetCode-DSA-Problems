class Solution {
    public long countCommas(long n) {
        if(n<=999) return 0;
        if(n<=999999) return 0 + (n-999)*1L;
        if(n<=999999999) return 0 + (999999-999)*1L + (n-999999)*2L;
        if(n<=999999999999L) return 0 + (999999-999)*1L + (999999999-999999)*2L + (n-999999999L)*3L;
        if(n<=999999999999999L) return 0 + (999999-999)*1L + (999999999-999999)*2L + (999999999999L-999999999L)*3L + (n-999999999999L)*4L;
        return 0 + (999999-999)*1L + (999999999-999999)*2L + (999999999999L-999999999L)*3L + (999999999999999L-999999999999L)*4L + (n-999999999999999L)*5L;
    }
}